/**
 * Generates samples/sample-products.csv and samples/sample-export.zip with the
 * real CSV/ZIP code, using clearly labelled SAMPLE products and the extension
 * icon as a stand-in image. Useful for checking how the CSV opens in Excel or
 * Google Sheets without visiting any website.
 *
 *   npm run sample
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildExportZip } from '../src/services/zip-exporter.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const placeholderImage = new Uint8Array(await readFile(path.join(root, 'icons', 'icon128.png')));

const SAMPLE_PRODUCTS = [
  ['walmart', '123456789', 'SAMPLE onn. 50” Class 4K UHD LED Roku Smart TV', '198.00', 'USD', 'https://www.walmart.com/ip/onn-50-Class-4K-UHD-LED-Roku-Smart-TV/123456789', 'https://i5.walmartimages.com/seo/sample_123456789.jpeg'],
  ['amazon', 'B0TEST0001', 'SAMPLE Soundwave Wireless Headphones, Active Noise Cancelling', '59.99', 'USD', 'https://www.amazon.com/dp/B0TEST0001', 'https://m.media-amazon.com/images/I/61img0001.jpg'],
  ['amazon', 'B0TEST0003', 'SAMPLE Acme Audio Kids Over-Ear Headphones', '15.99 - 29.99', 'USD', 'https://www.amazon.com/dp/B0TEST0003', 'https://m.media-amazon.com/images/I/61img0003.jpg'],
  ['target', '80000003', 'SAMPLE Arc Floor Lamp Brass - Project 62™ (no price shown)', '', '', 'https://www.target.com/p/floor-lamp-brass/-/A-80000003', 'https://target.scene7.com/is/image/Target/GUEST_lamp0003?wid=1200&hei=1200'],
  ['bestbuy', '6500001', 'SAMPLE HP - 14" Laptop - Intel Celeron - 4GB Memory', '179.99', 'USD', 'https://www.bestbuy.com/site/hp-14-laptop-intel-celeron/6500001.p?skuId=6500001', 'https://pisces.bbystatic.com/image2/BestBuy_US/images/products/6500/6500001_sd.jpg'],
  ['ebay', '256000000003', 'SAMPLE Vintage Film Camera 35mm (image download failed)', '45.00', 'CAD', 'https://www.ebay.com/itm/256000000003', 'https://i.ebayimg.com/images/g/IjKl0003/s-l1600.jpg'],
  ['ebay', '256000000005', '=SAMPLE formula-looking title (Excel shows it as text)', '350.00', 'USD', 'https://www.ebay.com/itm/256000000005', 'https://i.ebayimg.com/images/g/MnOp0005/s-l1600.jpg'],
].map(([platform, product_id, product_name, price, currency, product_url, image_url]) => ({
  platform, product_id, product_name, price, currency, product_url, image_url, image: '', image_candidates: [image_url],
}));

const { data, csv, summary } = await buildExportZip(SAMPLE_PRODUCTS, {
  outputType: 'uint8array',
  generatedAt: new Date('2026-01-01T12:00:00Z'),
  source: { note: 'Generated by scripts/make-sample.mjs - sample data, not real listings' },
  // Simulate one failed download to show what an empty image path looks like.
  downloadImage: async (candidates) =>
    candidates[0].includes('IjKl0003')
      ? { ok: false, error: { code: 'IMAGE_HTTP_ERROR', message: 'HTTP 404 (simulated)' } }
      : { ok: true, bytes: placeholderImage, ext: 'png', url: candidates[0] },
});

await mkdir(path.join(root, 'samples'), { recursive: true });
await writeFile(path.join(root, 'samples', 'sample-products.csv'), csv, 'utf8');
await writeFile(path.join(root, 'samples', 'sample-export.zip'), data);
console.log(`Wrote samples/sample-products.csv and samples/sample-export.zip (${summary.imagesSaved} images, ${summary.imagesFailed} failed).`);
